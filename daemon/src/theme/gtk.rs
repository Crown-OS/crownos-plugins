//! GTK named colors from the theme tokens, so GTK and libadwaita apps match.

use std::fmt::Write;

use crownos_config::schema::theme::parse_hex;
use crownplugin_model::ThemeManifest;

pub type Rgba = [f32; 4];

/// The handful of roles third-party toolkits understand, resolved from the
/// theme's tokens with a neutral fallback for any the theme leaves unset.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Palette {
    pub dark: bool,
    pub window_bg: Rgba,
    pub window_fg: Rgba,
    pub view_bg: Rgba,
    pub header_bg: Rgba,
    pub popover_bg: Rgba,
    pub border: Rgba,
    pub accent: Rgba,
    pub accent_fg: Rgba,
    pub muted: Rgba,
    pub danger: Rgba,
    pub success: Rgba,
    pub warning: Rgba,
}

fn hex(text: &str) -> Rgba {
    parse_hex(text).unwrap_or([0.0, 0.0, 0.0, 1.0])
}

impl Palette {
    pub fn of(theme: &ThemeManifest, dark: bool) -> Self {
        let tokens = if dark { &theme.tokens.dark } else { &theme.tokens.light };
        let pick = |token: &str, dark_default: &str, light_default: &str| {
            tokens
                .get(token)
                .and_then(|value| parse_hex(value))
                .unwrap_or_else(|| hex(if dark { dark_default } else { light_default }))
        };
        let accent = theme
            .tokens
            .accent
            .as_ref()
            .and_then(|accent| parse_hex(&accent.end))
            .unwrap_or_else(|| pick("accent.end", "#6d48e8", "#6d48e8"));
        Self {
            dark,
            window_bg: pick("surface.bg", "#1e1e22", "#f5f5f7"),
            window_fg: pick("text.primary", "#f0f0f2", "#1c1c1f"),
            view_bg: pick("surface.raised", "#26262b", "#ffffff"),
            header_bg: pick("surface.sunken", "#18181b", "#ebebef"),
            popover_bg: pick("popover.bg", "#2c2c31", "#ffffff"),
            border: pick("surface.border", "#ffffff24", "#0000001f"),
            accent,
            accent_fg: pick("text.on_accent", "#ffffff", "#ffffff"),
            muted: pick("text.muted", "#a0a0a8", "#6b6b73"),
            danger: pick("status.danger", "#e5484d", "#d93036"),
            success: pick("status.success", "#30a46c", "#218358"),
            warning: pick("status.warning", "#f5a524", "#b85c00"),
        }
    }
}

fn byte(channel: f32) -> u8 {
    (channel.clamp(0.0, 1.0) * 255.0).round() as u8
}

pub fn css_color([r, g, b, a]: Rgba) -> String {
    format!("rgba({}, {}, {}, {:.3})", byte(r), byte(g), byte(b), a)
}

pub fn css(palette: &Palette) -> String {
    let roles = [
        ("window_bg_color", palette.window_bg),
        ("window_fg_color", palette.window_fg),
        ("view_bg_color", palette.view_bg),
        ("view_fg_color", palette.window_fg),
        ("card_bg_color", palette.view_bg),
        ("card_fg_color", palette.window_fg),
        ("headerbar_bg_color", palette.header_bg),
        ("headerbar_fg_color", palette.window_fg),
        ("sidebar_bg_color", palette.header_bg),
        ("sidebar_fg_color", palette.window_fg),
        ("popover_bg_color", palette.popover_bg),
        ("popover_fg_color", palette.window_fg),
        ("dialog_bg_color", palette.popover_bg),
        ("dialog_fg_color", palette.window_fg),
        ("borders", palette.border),
        ("accent_color", palette.accent),
        ("accent_bg_color", palette.accent),
        ("accent_fg_color", palette.accent_fg),
        ("destructive_color", palette.danger),
        ("destructive_bg_color", palette.danger),
        ("success_color", palette.success),
        ("warning_color", palette.warning),
        ("error_color", palette.danger),
        ("theme_bg_color", palette.window_bg),
        ("theme_fg_color", palette.window_fg),
        ("theme_base_color", palette.view_bg),
        ("theme_text_color", palette.window_fg),
        ("theme_selected_bg_color", palette.accent),
        ("theme_selected_fg_color", palette.accent_fg),
    ];
    let mut css = String::from("/* Generated by crownplugind from the active CrownOS theme. */\n");
    for (name, color) in roles {
        let _ = writeln!(css, "@define-color {name} {};", css_color(color));
    }
    css
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colors_print_as_css_rgba() {
        assert_eq!(css_color([1.0, 0.0, 0.5, 1.0]), "rgba(255, 0, 128, 1.000)");
    }
}
